# Writes dev/build/jgecat.js (the grand-ending catalogue the game reads) from cat.py — the ONE source of names, pairs, titles (design §3).
# run: python3 dev/test/ge_guard/gen_js.py   (the guard dev/test/ge-guard.js checks the game copy matches this file)
import sys,os,json; here=os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0,here); from cat import *
R1={"O":0,"Q":1,"R":2,"T":3}; R2={"A":0,"U":1,"B":2}
out={}
for rid,rn,L in R:
    out[rid]={"n":rn,"e":[[x[0],x[1],x[2],R1[x[3]],R2[x[4]],x[5]]+list(titles(x)) for x in L]}
js=("/* ================= jgecat: GRAND ENDINGS catalogue (Đại kết cục, dev/design/GRAND_ENDINGS.md §3, r3) =================\n"
    "   GENERATED by dev/test/ge_guard/gen_js.py from dev/test/ge_guard/cat.py — never edit by hand (the variety guard checks it).\n"
    "   GE_CAT[branch] = {n: road name, e: 4 endings [node name, group 1-10, natural T/H/A, Ngã rẽ 1 (0 giữ phận · 1 nắm quyền · 2 rời cung · 3 theo người),\n"
    "   Ngã rẽ 2 (0 ân · 1 uy · 2 buông), summit, thiện title, ác title]}. GE_ID = identity names. */\n"
    "const GE_CAT="+json.dumps(out,ensure_ascii=False,separators=(",",":"))+";\n"
    "const GE_ID="+json.dumps(ID,ensure_ascii=False,separators=(",",":"))+";\n"
    "const GE_GROUP="+json.dumps(G,ensure_ascii=False,separators=(",",":"))+";\n")
open(os.path.join(here,'..','..','build','jgecat.js'),'w',encoding='utf-8').write(js)
print("jgecat.js",len(js),"bytes,",len(out),"branches")
