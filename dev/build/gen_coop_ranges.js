/* robot-coop-fix-2 r2 (law 4 ONE CORE): the co-op Worker cannot read BAL at run time, so its person-range table is GENERATED from the game's
   one source: BAL.personRange (dev/build/jbalpr.js, the whole file) + BAL.kh (the khí huyết numbers sucCap reads, jbal2.js `BAL.kh={…};`).
   usage: node dev/build/gen_coop_ranges.js            → writes coop/worker/src/ranges.gen.js (assemble.py runs it)
          node dev/build/gen_coop_ranges.js --check    → exit 1 when the committed file differs from BAL (coop/worker/test/range.test.mjs runs it) */
const vm=require('vm'),fs=require('fs'),path=require('path');
const ROOT=path.resolve(__dirname,'../..'),OUT=path.join(ROOT,'coop/worker/src/ranges.gen.js');
function build(){const ctx={BAL:{}};vm.createContext(ctx);
 vm.runInContext(fs.readFileSync(path.join(__dirname,'jbalpr.js'),'utf8'),ctx,{filename:'jbalpr.js'});
 const b2=fs.readFileSync(path.join(__dirname,'jbal2.js'),'utf8');const m=b2.match(/^BAL\.kh=(\{[\s\S]*?\});/m);if(!m)throw new Error('jbal2.js: BAL.kh={…}; not found');
 vm.runInContext('BAL.kh='+m[1],ctx);const B=ctx.BAL,J=x=>JSON.stringify(x);
 return `/* GENERATED by dev/build/gen_coop_ranges.js — DO NOT EDIT. Source: BAL.personRange (dev/build/jbalpr.js) + BAL.kh (dev/build/jbal2.js).
   coop/worker/test/range.test.mjs fails when this file differs from BAL. [lo, hi], null = no bound. */
export const STAT = ${J(B.personRange.stat)};
export const MAP = ${J(B.personRange.map)};
export const SUB = ${J(B.personRange.sub)};
export const WORLD = ${J(B.personRange.world)};
export const BODY = ${J(B.personRange.body)};
export const KH = ${J(B.kh)};
`}
const txt=build();
if(process.argv.includes('--check')){const cur=fs.existsSync(OUT)?fs.readFileSync(OUT,'utf8'):'';if(cur!==txt){console.error('coop/worker/src/ranges.gen.js is STALE vs BAL: run node dev/build/gen_coop_ranges.js');process.exit(1)}console.log('ranges.gen.js = BAL (personRange + kh)');process.exit(0)}
fs.writeFileSync(OUT,txt);console.log('wrote '+path.relative(ROOT,OUT));
