#!/usr/bin/env python3
"""SELSCENE-4: build dev/build/jselxd.js (data only) from the selection content files
(dev/handover/content/selscene/{yard.md, days.md, doidap.jsonl, hanhxu.jsonl}). Run after editing a content file:
  python3 dev/build/gen_selxd.py      (checks: every stance gain steps == loss steps, law 2/3; 4 stances; placeholders known)"""
import json,os,re,sys
D=os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','handover','content','selscene')
def lines(f):return [json.loads(l) for l in open(os.path.join(D,f),encoding='utf-8') if l.startswith('{')]
DROP={'src','tag','reactLines','bar'}
def slim(x):return {k:v for k,v in x.items() if k not in DROP}
err=[]
FIXPH={'{V}':'{victim}','{bystander1}':'{bystander}'}  # writer typos in yard.md (yd-012, yd-006), normalised here
def fixph(x):
  t=json.dumps(x,ensure_ascii=False)
  for a,b in FIXPH.items():t=t.replace(a,b)
  return json.loads(t)
seeds=[fixph(slim(x)) for x in lines('yard.md')+lines('days.md')]
for x in seeds:
  st=x['stances']
  if sorted(st)!=['benh','hoagiai','hua','ngoai']:err.append(x['id']+' stances')
  for k,s in st.items():
    g=sum(v for v in s['gain'].values());l=sum(v for v in s['loss'].values())
    if g!=l:err.append(f"{x['id']}.{k} gain {g} != loss {l}")
    for v in list(s['gain'].values())+list(s['loss'].values()):
      if not isinstance(v,int) or v<=0:err.append(f"{x['id']}.{k} step {v}")
  txt=json.dumps(x,ensure_ascii=False)
  for r in set(re.findall(r'\{(\w+)\}',txt)):
    if r not in x['roles'] and r not in ('bystander',):err.append(f"{x['id']} placeholder {r}")
tests=[slim(x) for x in lines('doidap.jsonl')+lines('hanhxu.jsonl')]
if err:print('\n'.join(err));sys.exit(1)
by={}
for x in seeds:by.setdefault(x['type'],[]).append(x)
out='/* ================= jselxd: SELECTION CONTENT (data only; GENERATED by dev/build/gen_selxd.py from dev/handover/content/selscene/*; do not edit by hand) =================\n   SELX_SEEDS.yard = waiting-yard dramas (day 2, SELW-YARD), .dorm = day-1 lodging dramas, .kept = day-3 dramas of the 4 kept (SELSCENE-4); SELX_TESTS = đối đáp + hành xử (SELW-TESTS2). */\n'
out+='const SELX_SEEDS='+json.dumps(by,ensure_ascii=False,separators=(',',':'))+';\n'
out+='const SELX_TESTS='+json.dumps(tests,ensure_ascii=False,separators=(',',':'))+';\n'
open(os.path.join(os.path.dirname(os.path.abspath(__file__)),'jselxd.js'),'w',encoding='utf-8').write(out)
print('jselxd.js:',{k:len(v) for k,v in by.items()},'tests',len(tests),len(out),'bytes')
