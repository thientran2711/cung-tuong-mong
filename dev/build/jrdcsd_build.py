#!/usr/bin/env python3
"""ORDER THIN P8: build dev/build/jrdcsd.js (window.RDCSD = composed-road rows) from the writer files.
usage: python3 dev/build/jrdcsd_build.py [files…] [--force]
  no files = every dev/handover/content/thin/rdseeds_*.md. Runs the validator first; any error stops the build (--force writes anyway).
The engine (dev/build/jroadc.js) registers each premise as a j67 arc and its chapters .5–.11 through jroad.js rdDef."""
import json, sys, os, glob
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'dev', 'test'))
import rdseeds_validate as RV

def main(argv):
    files = [a for a in argv if not a.startswith('--')] or sorted(glob.glob(os.path.join(ROOT, 'dev/handover/content/thin/rdseeds_*.md')))
    rows = RV.read_rows(files)
    v, C = RV.validate(rows)
    for x in v.E: print(x)
    if v.E and '--force' not in argv:
        print(f'jrdcsd_build: {len(v.E)} validator errors, nothing written (--force to write anyway)'); return 1
    out = []
    for r in rows:
        if '__bad' in r: continue
        r = {k: x for k, x in r.items() if not k.startswith('__')}
        out.append(r)
    js = ('/* GENERATED by dev/build/jrdcsd_build.py from ' + (', '.join(os.path.relpath(f, ROOT) for f in files) or 'no writer file') +
          ' — do not edit; edit the writer files (API P8) and rebuild. Read by jroadc.js. */\n'
          'window.RDCSD=' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
    open(os.path.join(ROOT, 'dev/build/jrdcsd.js'), 'w', encoding='utf-8').write(js)
    n = {t: sum(1 for r in out if r.get('type') == t) for t in ('prem', 'open', 'comp', 'turn', 'clim')}
    print(f'jrdcsd.js: {len(out)} rows {n} from {len(files)} file(s)')
    return 0

if __name__ == '__main__': sys.exit(main(sys.argv[1:]))
