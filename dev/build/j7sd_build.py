#!/usr/bin/env python3
"""Build dev/build/j7sd.js (const J7SEEDS=[...]) from the P2-SEEDS content file (one JSON seed per line). Runs the validator first.
usage: python3 dev/build/j7sd_build.py <path to j7seeds.md>   (the content file lives on the handover branch: dev/handover/content/thin/j7seeds.md)"""
import json,sys,os,subprocess
D=os.path.dirname(os.path.abspath(__file__));src=sys.argv[1]
if subprocess.call([sys.executable,os.path.join(D,'../test/j7seeds_validate.py'),src]):sys.exit("validator failed: fix the seeds first")
rows=[json.loads(l) for l in open(src,encoding='utf8') if l.lstrip().startswith('{')]
open(os.path.join(D,'j7sd.js'),'w',encoding='utf8').write("/* j7sd: ORDER THIN P2 composed intrigue seeds (GENERATED by dev/build/j7sd_build.py from dev/handover/content/thin/j7seeds.md; do not edit by hand) */\nconst J7SEEDS=[\n"+",\n".join(json.dumps(r,ensure_ascii=False,separators=(',',':')) for r in rows)+"];\n")
print("j7sd.js:",len(rows),"seeds")
