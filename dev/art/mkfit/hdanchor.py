#!/usr/bin/env python3
"""HD_ANCHOR — the ONE hoa điền target table (review/mg-play2, owner OD 20/11 ~07:45Z + ~07:55Z).
Owner: the target stays HIDDEN, but it must sit exactly on the natural spot of THAT painted face (the point between the brows), so the face
itself guides her and the hidden mark never disagrees with the picture. One row per portrait of HER (every por-/fig- picture of the player
faces she can wear — the 32 consort faces c01–c32 (every dress tier / age / trung y / kc / ngheo / maid dress) and the old player looks —
that has face points in dev/art/mkfit/consort-*.json + player-*.json = img/mk-fit), computed by one rule and LOOKED at (contact sheet, --sheet):
   spot = midpoint of the two brows' inner ends (each = mean of the 2 brow-contour points nearest the face midline),
          raised UP x eye distance perpendicular to the eye line (UP = BAL.hd.up, read from dev/build/jhd.js so the number lives once).
Row = [x, y, ed, ang10]: x,y in 1/4000 of the picture width / height; ed = eye distance in 1/4000 of the picture WIDTH; ang10 = eye-line
angle in tenths of a degree. The game (jhd.js hdAnchor) reads the row first, so the board never waits for the face-points file.
usage: python3 -I dev/art/mkfit/hdanchor.py            rewrite the HD_ANCHOR block in dev/build/jhd.js
       python3 -I dev/art/mkfit/hdanchor.py --check    exit 1 when the block differs from what the rule gives (test hook)
       python3 -I dev/art/mkfit/hdanchor.py --sheet DIR/out.png  (needs the portraits in DIR, e.g. fetched from the CDN) contact sheet"""
import json, glob, math, os, re, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../.."))
JHD = os.path.join(ROOT, "dev/build/jhd.js")
src = open(JHD, encoding="utf-8").read()
UP = float(re.search(r"\bup:([0-9.]+)", src).group(1))
def anchor(m, A):
    P = lambda i: (m[2 * i] / 4000, m[2 * i + 1] / 4000 * A)  # both in picture-WIDTH units
    eye = lambda s: (sum(P(s + i)[0] for i in range(10)) / 10, sum(P(s + i)[1] for i in range(10)) / 10)
    E = sorted([eye(20), eye(30)])
    ed = math.hypot(E[1][0] - E[0][0], E[1][1] - E[0][1]); ang = math.atan2(E[1][1] - E[0][1], E[1][0] - E[0][0]); mx = (E[0][0] + E[1][0]) / 2
    def inner(s):
        L = sorted([P(s + i) for i in range(10)], key=lambda p: abs(p[0] - mx)); return ((L[0][0] + L[1][0]) / 2, (L[0][1] + L[1][1]) / 2)
    a, b = inner(40), inner(50); mid = ((a[0] + b[0]) / 2, (a[1] + b[1]) / 2)
    at = (mid[0] + math.sin(ang) * UP * ed, mid[1] - math.cos(ang) * UP * ed)
    return [round(at[0] * 4000), round(at[1] / A * 4000), round(ed * 4000), round(math.degrees(ang) * 10)]

# picture aspect (H/W) per file: from the toil-fit table when present, else the kind's usual aspect (por 506/384, fig measured once)
fit = {}
try:
    f2 = json.load(open(os.path.join(ROOT, "dev/art/toil-fit2.json"))); fit = f2.get("fit", f2)
except Exception:
    pass
DEF_A = {"por": 506 / 384, "fig": None}

def aspect(n):
    t = fit.get(n)
    if t and len(t) > 8 and t[8]: return float(t[8])
    if n.startswith("por-"): return DEF_A["por"]
    return None

rows = {}
skip = []
for f in sorted(glob.glob(os.path.join(ROOT, "dev/art/mkfit/consort-*.json")) + glob.glob(os.path.join(ROOT, "dev/art/mkfit/player-*.json"))):
    for n, m in sorted(json.load(open(f)).items()):
        if len(m) < 120: skip.append((n, "short")); continue
        A = aspect(n)
        if A is None: skip.append((n, "no aspect")); continue
        rows[n] = anchor(m, A)

def block():
    # compact: one string per face; row = "<p|f><rest>:x:y:ed:ang10", rows split by a space; key = (por|fig)-<face>-<rest>.webp
    G = {}
    for n, r in sorted(rows.items()):
        m = re.match(r"^(por|fig)-([a-z]+-[a-z]*\d+)-(.+)\.webp$", n)
        if not m: skip.append((n, "name")); continue
        G.setdefault(m.group(2), []).append("%s%s:%s" % (m.group(1)[0], m.group(3), ":".join(str(v) for v in r)))
    body = ",\n".join('"%s":"%s"' % (k, " ".join(v)) for k, v in sorted(G.items()))
    return "/* HD_ANCHOR:BEGIN (generated by dev/art/mkfit/hdanchor.py from img/mk-fit; do not edit by hand, re-run the script) */\nconst HD_ANC_RAW={\n" + body + "};\n/* HD_ANCHOR:END */"

if __name__ == "__main__":
    a = sys.argv[1:]
    B = block()
    pat = re.compile(r"/\* HD_ANCHOR:BEGIN.*?HD_ANCHOR:END \*/", re.S)
    if "--check" in a:
        m = pat.search(src)
        ok = bool(m) and m.group(0) == B
        print("HD_ANCHOR rows %d, skipped %d %s -> %s" % (len(rows), len(skip), skip[:4], "OK" if ok else "DIFFERS (re-run hdanchor.py)"))
        sys.exit(0 if ok else 1)
    if "--sheet" in a:
        from PIL import Image, ImageDraw
        out = a[a.index("--sheet") + 1]; d = os.path.dirname(out)
        L = [n for n in sorted(rows) if os.path.exists(os.path.join(d, n))]
        T = []
        for n in L:
            im = Image.open(os.path.join(d, n)).convert("RGB"); W, H = im.size; x, y, ed, _ = rows[n]; x, y, ed = x / 4000 * W, y / 4000 * H, ed / 4000 * W
            g = ImageDraw.Draw(im); g.ellipse([x - ed * .12, y - ed * .12, x + ed * .12, y + ed * .12], outline=(255, 0, 0), width=2); g.line([x - 3, y, x + 3, y], fill=(255, 0, 0)); g.line([x, y - 3, x, y + 3], fill=(255, 0, 0))
            c = im.crop((int(x - ed * 1.2), int(y - ed * .8), int(x + ed * 1.2), int(y + ed * 1.1))).resize((240, 190)); ImageDraw.Draw(c).text((3, 3), n[11:-5], fill=(200, 0, 0)); T.append(c)
        S = Image.new("RGB", (240 * 5, 190 * ((len(T) + 4) // 5)), "white")
        for i, t in enumerate(T): S.paste(t, ((i % 5) * 240, (i // 5) * 190))
        S.save(out); print("sheet", out, len(T)); sys.exit(0)
    if not pat.search(src): print("no HD_ANCHOR block in jhd.js"); sys.exit(1)
    open(JHD, "w", encoding="utf-8").write(pat.sub(lambda _: B, src))
    print("HD_ANCHOR rows %d written, skipped %s" % (len(rows), skip))
