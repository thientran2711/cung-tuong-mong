import os, re
ART = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(ART))

def cut(path, start, end_at):
    """the exact text in `path` from `start` up to and including the first `end_at` after it (copied, not typed)."""
    t = open(os.path.join(ROOT, path), encoding="utf-8").read()
    i = t.index(start); j = t.index(end_at, i) + len(end_at)
    s = t[i:j]
    return s, t[:i].count("\n") + 1

