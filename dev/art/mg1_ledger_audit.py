#!/usr/bin/env python3
"""MG1 job 4 (owner B25): every gen in dev/art/gen_ledger.jsonl whose prompt lacks the MASTER block (dev/art/MASTER_COMMON.txt, 14 sentences).
Prompt text per line = magnific_prompt > prompt > the prompt_file it names (if that file is in the repo). Read only; writes
dev/handover/reports/MG1-ledger-audit.md.  Run: python3 dev/art/mg1_ledger_audit.py"""
import os, sys, json, re, collections
ART = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(ART))
sys.path.insert(0, ART); import master_common as MC

S = MC.sentences(); IDS = MC.ids()


def text_of(e):
    for k in ("magnific_prompt", "prompt"):
        if isinstance(e.get(k), str) and len(e[k]) > 40: return e[k], k
    pf = e.get("prompt_file")
    if isinstance(pf, str):
        p = os.path.join(ROOT, pf.split("#")[0].split(" ")[0])
        if os.path.isfile(p): return open(p, encoding="utf-8", errors="replace").read(), "prompt_file"
    return None, None


def main():
    per = collections.OrderedDict(); rows = []
    for ln, l in enumerate(open(os.path.join(ART, "gen_ledger.jsonl"), encoding="utf-8"), 1):
        if not l.strip(): continue
        e = json.loads(l); kind = str(e.get("kind") or e.get("set") or "(no kind)")
        c = per.setdefault(kind, collections.Counter()); c["gens"] += 1
        t, src = text_of(e)
        if t is None: c["no prompt text"] += 1; rows.append((kind, e.get("gen_id"), ln, "no prompt text", "")); continue
        t = re.sub(r"\s+", " ", t); have = [k for k, s in zip(IDS, S) if re.sub(r"\s+", " ", s) in t]
        if len(have) == len(S): c["full block"] += 1; continue
        c["lacks block"] += 1; c[f"has {len(have)}/14"] += 0
        rows.append((kind, e.get("gen_id"), ln, f"{len(have)}/14", ",".join(k for k in IDS if k not in have)))
    tot = collections.Counter()
    for c in per.values(): tot.update(c)
    L = ["# MG1 ledger audit — gens whose prompt lacks the MASTER block (owner B25)", "",
         "Generated by `python3 dev/art/mg1_ledger_audit.py` (read only). Source dev/art/gen_ledger.jsonl; prompt = magnific_prompt > prompt > prompt_file. "
         "A gen 'lacks the block' when any of the 14 master sentences (dev/art/MASTER_COMMON.txt) is not in its prompt verbatim. "
         "Every gen before MG1 was made without the master block, so this is the expected picture: nothing is redrawn because of it (Lượt 757: base pictures are NOT redrawn).", "",
         f"Totals: {tot['gens']} gens · lacks block {tot['lacks block']} · full block {tot['full block']} · no prompt text recorded {tot['no prompt text']}", "",
         "## Per kind", "", "| kind | gens | lacks block | full block | no prompt text |", "|---|---|---|---|---|"]
    for k, c in sorted(per.items(), key=lambda kv: -kv[1]["gens"]):
        L.append(f"| {k} | {c['gens']} | {c['lacks block']} | {c['full block']} | {c['no prompt text']} |")
    have = collections.Counter(r[3] for r in rows)
    L += ["", "## How much of the block the old prompts already had", "", "| master sentences present | gens |", "|---|---|"]
    L += [f"| {k} | {v} |" for k, v in sorted(have.items(), key=lambda kv: (len(kv[0]), kv[0]))]
    L += ["", "## Ids (kind · gen_id · ledger line · present · missing master ids)", "", "| kind | gen_id | line | present | missing |", "|---|---|---|---|---|"]
    L += [f"| {k} | {g} | {ln} | {p} | {m} |" for k, g, ln, p, m in rows]
    out = os.path.join(ROOT, "dev/handover/reports/MG1-ledger-audit.md")
    open(out, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("\n".join(L[4:8 + len(per) + 2])); print("wrote", os.path.relpath(out, ROOT))


if __name__ == "__main__":
    main()
